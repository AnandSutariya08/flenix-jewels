// ── Seed ─────────────────────────────────────────────────────────────────────

async function seed() {
  console.log('Seeding diamond categories...');
  for (const cat of DIAMOND_CATEGORIES) {
    await setDoc(doc(db, 'diamond-categories', cat.id), cat);
    console.log(`  ✓ Category: ${cat.name}`);
  }

  console.log('\nSeeding diamonds...');
  for (const diamond of DIAMONDS) {
    await setDoc(doc(db, 'diamonds', diamond.id), diamond);
    console.log(`  ✓ ${diamond.name}`);
  }

  console.log('\n✅ Done! Seeded', DIAMOND_CATEGORIES.length, 'categories and', DIAMONDS.length, 'diamonds.');
  process.exit(0);
}

seed().catch(err => {
  console.error('Seed failed:', err);
  process.exit(1);
});
